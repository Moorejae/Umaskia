import { initializeApp } from 'firebase/app';
import {
  getAuth,
  signInWithPopup,
  GoogleAuthProvider,
  onAuthStateChanged,
  User,
} from 'firebase/auth';
import firebaseConfig from '../../firebase-applet-config.json';
import { WebsiteSkill } from '../types/skill';
import { compileSkillToMarkdown } from '../data/websiteSkillsData';

const app = initializeApp(firebaseConfig);
const auth = getAuth(app);

export const SCOPES = ['https://www.googleapis.com/auth/documents'];

const provider = new GoogleAuthProvider();
SCOPES.forEach((scope) => provider.addScope(scope));
provider.setCustomParameters({
  prompt: 'consent',
});

// In-memory token storage only (never persisted to localStorage or sessionStorage)
let isSigningIn = false;
let cachedAccessToken: string | null = null;

export const initAuth = (
  onAuthSuccess?: (user: User, token: string) => void,
  onAuthFailure?: () => void
) => {
  return onAuthStateChanged(auth, async (user: User | null) => {
    if (user) {
      if (cachedAccessToken) {
        if (onAuthSuccess) onAuthSuccess(user, cachedAccessToken);
      } else if (!isSigningIn) {
        cachedAccessToken = null;
        if (onAuthFailure) onAuthFailure();
      }
    } else {
      cachedAccessToken = null;
      if (onAuthFailure) onAuthFailure();
    }
  });
};

export const googleSignIn = async (): Promise<{
  user: User;
  accessToken: string;
} | null> => {
  try {
    isSigningIn = true;
    const result = await signInWithPopup(auth, provider);
    const credential = GoogleAuthProvider.credentialFromResult(result);
    if (!credential?.accessToken) {
      throw new Error('Failed to retrieve Google Docs OAuth access token.');
    }
    cachedAccessToken = credential.accessToken;
    return { user: result.user, accessToken: cachedAccessToken };
  } catch (error) {
    console.error('Google Sign-In error:', error);
    throw error;
  } finally {
    isSigningIn = false;
  }
};

export const getAccessToken = async (): Promise<string | null> => {
  return cachedAccessToken;
};

export const logout = async () => {
  await auth.signOut();
  cachedAccessToken = null;
};

export function extractGoogleDocId(input: string): string {
  const trimmed = input.trim();
  const match = trimmed.match(/\/document\/d\/([a-zA-Z0-9-_]+)/);
  if (match && match[1]) {
    return match[1];
  }
  return trimmed;
}

export function buildUnifiedGoogleDocContent(
  docTitle: string,
  skills: WebsiteSkill[]
): string {
  const timestamp = new Date().toISOString().split('T')[0];
  const tocLines = skills.map(
    (s, idx) =>
      `${String(idx + 1).padStart(2, '0')}. [${s.category}] ${s.name} (skills/${s.slug}/SKILL.md) — Sub-Archetypes: ${s.subArchetypes.join(', ')}`
  );

  const headerBlock = [
    `${docTitle}`,
    `Generated by SkillFoundry · Last Updated: ${timestamp} · Total Website Archetype Skills: ${skills.length}`,
    '',
    '================================================================================',
    '00. EXECUTIVE INDEX & AGENTIC SYSTEM ROUTING INSTRUCTIONS',
    '================================================================================',
    '',
    'HOW AI CODING AGENTS USE THIS MASTER SPECIFICATION:',
    '1. Classify the target client brief or website build request against the Macro Taxonomy Index below.',
    '2. Load the matching SKILL.md specification block (or combine 2 hybrid skills when building multi-modal platforms).',
    '3. Enforce all 3 mandatory engineering layers in order: (A) YAML & UX Conversion Flow, (B) 60-30-10 Visual Design Constitution & Typography, and (C) Component Tree, State Schema & JSON-LD Structured Data.',
    '4. Verify the final build against the Domain Anti-Slop Bans before shipping or deploying for client sale.',
    '',
    'MASTER TAXONOMY TABLE OF CONTENTS:',
    ...tocLines,
    '',
  ].join('\n');

  const skillBlocks = skills.map((skill, idx) => {
    const num = String(idx + 1).padStart(2, '0');
    const md = compileSkillToMarkdown(skill);
    return [
      '================================================================================',
      `SKILL ${num} OF ${String(skills.length).padStart(2, '0')}: ${skill.name.toUpperCase()}`,
      `FILE PATH: /skills/${skill.slug}/SKILL.md`,
      `CATEGORY: ${skill.category} · SUB-ARCHETYPES: ${skill.subArchetypes.join(' | ')}`,
      '================================================================================',
      '',
      md,
      '',
    ].join('\n');
  });

  return `${headerBlock}\n${skillBlocks.join('\n')}\n`;
}

/**
 * Creates a brand-new unified Master Google Doc and writes all selected skills into it.
 */
export async function createMasterGoogleDoc(
  docTitle: string,
  skills: WebsiteSkill[]
): Promise<{ documentId: string; title: string; url: string }> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Authentication required. Please sign in with Google first.');
  }

  // Step 1: Create the blank document via Google Docs API
  const createRes = await fetch('https://docs.googleapis.com/v1/documents', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title: docTitle,
    }),
  });

  if (!createRes.ok) {
    const errBody = await createRes.text();
    throw new Error(`Failed to create Google Doc (${createRes.status}): ${errBody}`);
  }

  const createdDoc = await createRes.json();
  const documentId: string = createdDoc.documentId;

  // Step 2: Populate the unified master handbook content via batchUpdate
  const fullContent = buildUnifiedGoogleDocContent(docTitle, skills);
  const firstLineEnd = 1 + docTitle.length;

  const updateRes = await fetch(
    `https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        requests: [
          {
            insertText: {
              location: { index: 1 },
              text: fullContent,
            },
          },
          {
            updateParagraphStyle: {
              range: {
                startIndex: 1,
                endIndex: firstLineEnd,
              },
              paragraphStyle: {
                namedStyleType: 'HEADING_1',
              },
              fields: 'namedStyleType',
            },
          },
        ],
      }),
    }
  );

  if (!updateRes.ok) {
    const errBody = await updateRes.text();
    throw new Error(`Created document but failed to write skill contents (${updateRes.status}): ${errBody}`);
  }

  return {
    documentId,
    title: docTitle,
    url: `https://docs.google.com/document/d/${documentId}/edit`,
  };
}

/**
 * Fetches metadata for an existing Google Doc before appending (so the confirmation modal can show the exact document title).
 */
export async function getExistingGoogleDocInfo(
  docIdOrUrl: string
): Promise<{ documentId: string; title: string; endIndex: number }> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Authentication required. Please sign in with Google first.');
  }

  const documentId = extractGoogleDocId(docIdOrUrl);
  if (!documentId) {
    throw new Error('Please enter a valid Google Doc URL or Document ID.');
  }

  const getRes = await fetch(
    `https://docs.googleapis.com/v1/documents/${documentId}`,
    {
      headers: {
        Authorization: `Bearer ${token}`,
      },
    }
  );

  if (!getRes.ok) {
    const errBody = await getRes.text();
    throw new Error(`Could not access Google Doc (${getRes.status}). Verify the URL/ID and permissions. ${errBody}`);
  }

  const docData = await getRes.json();
  const contentArray = docData.body?.content || [];
  const lastElement = contentArray[contentArray.length - 1];
  const endIndex = lastElement?.endIndex ? Math.max(1, lastElement.endIndex - 1) : 1;

  return {
    documentId,
    title: docData.title || 'Untitled Google Doc',
    endIndex,
  };
}

/**
 * Appends skills to an existing Google Doc (MUST only be called after explicit user confirmation in the UI modal).
 */
export async function appendSkillsToExistingGoogleDoc(
  documentId: string,
  docTitle: string,
  endIndex: number,
  skills: WebsiteSkill[]
): Promise<{ documentId: string; title: string; url: string }> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Authentication required. Please sign in with Google first.');
  }

  const payloadText = `\n\n${buildUnifiedGoogleDocContent(
    `Appended Agentic Website Skills (${skills.length} Skills)`,
    skills
  )}`;

  const updateRes = await fetch(
    `https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        requests: [
          {
            insertText: {
              location: { index: endIndex },
              text: payloadText,
            },
          },
        ],
      }),
    }
  );

  if (!updateRes.ok) {
    const errBody = await updateRes.text();
    throw new Error(`Failed to append skills to Google Doc (${updateRes.status}): ${errBody}`);
  }

  return {
    documentId,
    title: docTitle,
    url: `https://docs.google.com/document/d/${documentId}/edit`,
  };
}
